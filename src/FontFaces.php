<?php
declare(strict_types=1);

namespace Jh2Pdf;

/**
 * Gera o CSS `@font-face` do NAVEGADOR a partir das mesmas fontes que o PDF usa ({@see FontIndex}: addFont + pastas).
 * Para o PDF sair idêntico à tela, o navegador precisa medir com os MESMOS arquivos que o servidor embute; gerando o CSS daqui,
 * nunca há duas listas de fontes para manter em sincronia.
 *
 *     // uma vez, ao publicar (a leitura dos nomes nos TTF é lenta demais para fazer a cada requisição):
 *     file_put_contents('public/fonts.css', Jh2Pdf\FontFaces::css($options, '/fonts/'));
 *
 * Ou pela linha de comando: `php tools/fonts-css.php --dir fonts --url /fonts/ --out public/fonts.css`.
 */
final class FontFaces
{
    private const DISPLAY = ['auto', 'block', 'swap', 'fallback', 'optional'];

    /**
     * @param string|callable(string):string $url  prefixo da URL dos arquivos (usa o nome do arquivo depois dele) ou função arquivo → URL
     * @param string $display  `font-display`; `block` (padrão) evita medir com a fonte de reserva enquanto a fonte carrega
     */
    public static function css(Options $o, string|callable $url = '', string $display = 'block'): string
    {
        $display = in_array($display, self::DISPLAY, true) ? $display : 'block';
        $index = new FontIndex($o);
        $out = ["/* @font-face for every font the PDF can embed, generated by Jh2Pdf\\FontFaces: the browser must measure with the SAME files. */"];
        foreach ($index->families() as $slug) {
            $faces = $index->faces($slug);
            ksort($faces);
            $family = $index->name($slug);
            foreach ($faces as $weight => $styles) {
                ksort($styles);
                foreach ($styles as $italic => $file) {
                    $name = $family ?? self::familyName($file, $slug);
                    $href = is_string($url) ? $url . rawurlencode(basename($file)) : (string)$url($file);
                    $out[] = sprintf("@font-face { font-family: '%s'; font-weight: %d; font-style: %s; font-display: %s; src: url('%s') format('truetype'); }",
                        self::esc($name), $weight, $italic ? 'italic' : 'normal', $display, self::esc($href));
                }
            }
        }
        return implode("\n", $out) . "\n";
    }

    /**
     * O nome da família como o CSS da página o escreve ("DM Sans"), lido de dentro do TTF. Só vale o nome que gera o mesmo slug do arquivo
     * (é por ele que o servidor acha a fonte); sem nenhum, usa o nome do arquivo com iniciais maiúsculas.
     */
    public static function familyName(string $file, string $slug): string
    {
        foreach (self::candidates($file) as $name) {
            if (FontIndex::slug($name) === $slug) return $name;
        }
        return ucwords(str_replace('-', ' ', $slug));
    }

    /** @return string[]  nomes da família dentro do TTF: tipográfico (16), o da família (1) e este sem as últimas palavras ("Inter Medium" → "Inter") */
    private static function candidates(string $file): array
    {
        if (!class_exists(\FontLib\Font::class)) return [];
        try {
            $font = \FontLib\Font::load($file);
            if ($font === null) return [];
            $font->parse();
            $rec = $font->getData('name', 'records');
            $font->close();
        } catch (\Throwable) {
            return [];
        }
        $names = [];
        foreach ([16, 1] as $id) {
            $n = isset($rec[$id]) ? trim((string)$rec[$id]->string) : '';
            if ($n === '') continue;
            $names[] = $n;
            for ($i = 0; $i < 3 && str_contains($n, ' '); $i++) {
                $n = substr($n, 0, (int)strrpos($n, ' '));
                $names[] = $n;
            }
        }
        return $names;
    }

    private static function esc(string $v): string
    {
        return addcslashes((string)preg_replace('/[\x00-\x1F\x7F]+/', '', $v), "'\\");
    }
}
